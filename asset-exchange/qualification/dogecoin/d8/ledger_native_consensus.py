def sha256d(raw):
    return hashlib.sha256(hashlib.sha256(raw).digest()).digest()


def require_report(report):
    """Independently reserialize every public input and exact signature before C ABI."""
    require(type(report) is dict and report.get("scope") ==
        "SYNTHETIC_HTLC_REFUND_DIGEST_SIGNED_IN_MAINNET_DOGE_APP_ONLY", "scope mismatch")
    for key, value in (
        ("D8_status", "BLOCKED"),
        ("ledger_app_network", "DOGE_MAINNET_PARAMETERS"),
        ("dogecoin_regtest_network_authenticated", False),
        ("native_consensus_cltv_verified_for_this_signature", False),
        ("independent_on_device_htlc_terms_displayed", False),
        ("hardware_device_present", False),
        ("real_doge_used", 0), ("broadcasts", 0),
        ("signature_on_synthetic_htlc_refund_digest_verified", True),
    ):
        require(type(report.get(key)) is type(value) and report[key] == value,
                "untrusted Ledger emulator report: " + key)
    candidate = report.get("native_consensus_candidate")
    require(type(candidate) is dict, "public native candidate is absent")
    exact_keys = {
        "signed_transaction_hex", "signed_transaction_sha256",
        "synthetic_funding_hex", "script_pubkey_hex", "redeem_script_hex",
        "signature_hex", "signature_low_s", "expected_native_flags",
        "input_index", "fake_prevout", "reviewed_network_in_firmware",
        "hardware_qualified", "broadcasts",
    }
    require(set(candidate) == exact_keys, "unexpected native candidate fields")
    for key, value in (
        ("expected_native_flags", 517), ("input_index", 0),
        ("fake_prevout", FAKE_INPUT_TXID),
        ("reviewed_network_in_firmware", "dogecoin-mainnet"),
        ("hardware_qualified", False), ("broadcasts", 0),
    ):
        require(type(candidate[key]) is type(value) and candidate[key] == value,
                "native candidate scope changed: " + key)
    def read_hex(key, maximum):
        raw = candidate[key]
        require(type(raw) is str and 0 < len(raw) <= 2 * maximum
                and re.fullmatch(r"(?:[0-9a-f]{2})+", raw), "bad native " + key)
        return bytes.fromhex(raw)
    signed = read_hex("signed_transaction_hex", 1000)
    funding = read_hex("synthetic_funding_hex", 512)
    script_pubkey = read_hex("script_pubkey_hex", 23)
    redeem = read_hex("redeem_script_hex", 150)
    signature = read_hex("signature_hex", 73)
    require(signature[-1:] == b"\x01" and 9 <= len(signature) <= 73,
            "only canonical SIGHASH_ALL signature accepted")
    require(len(script_pubkey) == 23 and script_pubkey[0:2] == b"\xa9\x14"
            and script_pubkey[-1:] == b"\x87", "not exact legacy P2SH output")
    parsed = decode_htlc(redeem)
    require(parsed.redeem == redeem and parsed.output == script_pubkey
            and parsed.claim_public == CLAIM_PUB and parsed.lock == LOCK,
            "noncanonical or modified D2 HTLC terms")
    # Funding bytes are deliberately impossible/unknown on chain and are
    # rederived, never trusted as an actual UTXO/confirmed value.
    expected_funding = transaction(FAKE_INPUT_TXID, 0, b"",
                                    [(FUNDED, script_pubkey)], 0, 0xffffffff)
    require(funding == expected_funding,
            "unfunded signed Ledger fixture no longer matches exact funding template")
    funding_id = sha256d(funding)[::-1].hex()
    script_sig = push(signature) + b"\x00" + push(redeem)
    expected_signed = transaction(funding_id, 0, script_sig, [(PAID, DEST)], LOCK, SEQ)
    require(signed == expected_signed, "unfunded Ledger refund serialization differs")
    require(hashlib.sha256(signed).hexdigest() == candidate["signed_transaction_sha256"],
            "Ledger refund SHA256 differs")
    require(hashlib.sha256(script_sig).hexdigest() == report["synthetic_refund_scriptSig_sha256"],
            "refund scriptSig SHA256 changed")
    require(hashlib.sha256(redeem).hexdigest() == report["contract_redeem_sha256"],
            "redeemScript commitment differs")
    require(hashlib.sha256(script_pubkey).hexdigest() == report["contract_p2sh_sha256"],
            "P2SH commitment differs")
    require(type(report["contract_lock_height"]) is int
            and report["contract_lock_height"] == LOCK and type(report["contract_sequence"]) is int
            and report["contract_sequence"] == SEQ, "lock or sequence changed")
    s = decode_der(signature[:-1])[1]
    require(type(candidate["signature_low_s"]) is bool
            and candidate["signature_low_s"] is (s <= ORDER // 2),
            "reported low-S state does not match signature")
    # The D2 implementation of SIGHASH_ALL is independent from our Speculos
    # streaming encoder. Native C ABI will verify the actual scriptSig.
    digest = sighash(funding_id, 0, redeem, [(PAID, DEST)], LOCK, SEQ)
    require(type(digest) is bytes and len(digest) == 32,
            "canonical D2 refund digest missing")
    return {
        "signed": signed,
        "funding": funding,
        "script": script_pubkey,
        "redeem": redeem,
        "signature": signature,
        "script_sig": script_sig,
        "funding_txid": funding_id,
        "sighash": digest,
        "low_s": candidate["signature_low_s"],
    }


def native_cases(model):
    """Construct negative spend transactions with *unchanged* Ledger signature."""
    txid = model["funding_txid"]
    sig = model["signature"]
    redeem = model["redeem"]
    signed_script = model["script_sig"]
    expected = model["signed"]
    lowlock = transaction(txid, 0, signed_script, [(PAID, DEST)], LOCK - 1, SEQ)
    wrongseq = transaction(txid, 0, signed_script, [(PAID, DEST)], LOCK, 0xffffffff)
    earlyseq = transaction(txid, 0, signed_script, [(PAID, DEST)], LOCK, SEQ - 1)
    other_dest = bytes.fromhex("76a914" + "43" * 20 + "88ac")
    other_redeem = redeem[:-35] + bytes([redeem[-35] ^ 1]) + redeem[-34:]
    branch_claim = push(sig) + b"\x51" + push(redeem)
    other_signature = sig[:-2] + bytes([sig[-2] ^ 1]) + sig[-1:]
    return [
        ("ledger_exact_htlc_refund", expected, 1),
        ("mutation_output_value", transaction(txid, 0, signed_script, [(PAID - 1, DEST)], LOCK, SEQ), 0),
        ("mutation_destination", transaction(txid, 0, signed_script, [(PAID, other_dest)], LOCK, SEQ), 0),
        ("mutation_cltv_early", lowlock, 0),
        ("mutation_final_sequence", wrongseq, 0),
        ("mutation_nonfinal_sequence", earlyseq, 0),
        ("mutation_funding_outpoint", transaction("12" * 32, 0, signed_script, [(PAID, DEST)], LOCK, SEQ), 0),
        ("mutation_funding_index", transaction(txid, 1, signed_script, [(PAID, DEST)], LOCK, SEQ), 0),
        ("mutation_redeem_script", transaction(txid, 0, push(sig) + b"\x00" + push(other_redeem),
                                              [(PAID, DEST)], LOCK, SEQ), 0),
        ("mutation_branch_selector", transaction(txid, 0, branch_claim, [(PAID, DEST)], LOCK, SEQ), 0),
        ("mutation_signature_byte", transaction(txid, 0, push(other_signature) + b"\x00" + push(redeem),
                                                [(PAID, DEST)], LOCK, SEQ), 0),
        ("mutation_sighash_type", transaction(txid, 0, push(sig[:-1] + b"\x02") + b"\x00" + push(redeem),
                                             [(PAID, DEST)], LOCK, SEQ), 0),
    ]


def native_check(model, path):
    """One exact native-positive and 11 negative script-input checks, zero chain."""
    verify = native_verifier(path)
    cases = []
    for name, raw, expected in native_cases(model):
        result = verify(model["script"], raw)
        require(result == {"result": expected, "error": 0, "flags": FLAGS},
                "source-qualified Dogecoin native verification failed: " + name)
        cases.append({
            "name": name, "expectedResult": expected,
            "observedResult": result["result"], "error": result["error"],
            "flags": result["flags"], "transactionSha256": hashlib.sha256(raw).hexdigest(),
        })
    return cases


def read_bounded(path):
    location = Path(path)
    fd = os.open(location, os.O_RDONLY | os.O_CLOEXEC | os.O_NOFOLLOW)
    try:
        st = os.fstat(fd)
        require(stat.S_ISREG(st.st_mode) and st.st_nlink == 1 and
                0 < st.st_size <= MAX_REPORT, "bounded regular Ledger public report required")
        data = os.read(fd, MAX_REPORT + 1)
        require(len(data) <= MAX_REPORT and len(data) == st.st_size,
                "Ledger report changed/oversized")
    finally:
        os.close(fd)
    def no_duplicates(pairs):
        obj = {}
        for key, value in pairs:
            require(key not in obj, "duplicate JSON key in native candidate report")
            obj[key] = value
        return obj
    return json.loads(data, object_pairs_hook=no_duplicates)


